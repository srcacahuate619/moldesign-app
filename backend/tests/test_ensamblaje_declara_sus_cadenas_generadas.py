"""El receptor declara qué cadenas se generaron por simetría y con qué operador (FEP-06-PRE, P09, 2026-10-24).

En 6SXC el sitio se forma entre la cadena A del depósito y una cadena C que es la A transformada por el operador BIOMT 3
del REMARK 350 (887 átomos pesados a 0,0 Å). El paquete decía «cadena A · sitio entre A+C» sin decir de dónde salía C, y
dos revisores la dieron por una cadena sin origen.
"""
from __future__ import annotations

from core.i18n_plantillas import _PARECE_CASTELLANO
from services.chemistry.ensamblaje_biologico import generar_unidad_biologica
from services.dossier.localization import traducir_dossier
from tests.test_preparacion_auditoria import _auditar, _con_procedencia, _requisito

_DEPOSITO = """REMARK 350 BIOMOLECULE: 1
REMARK 350   BIOMT1   1  1.000000  0.000000  0.000000        0.00000
REMARK 350   BIOMT2   1  0.000000  1.000000  0.000000        0.00000
REMARK 350   BIOMT3   1  0.000000  0.000000  1.000000        0.00000
REMARK 350   BIOMT1   2 -1.000000  0.000000  0.000000        0.00000
REMARK 350   BIOMT2   2  0.000000 -1.000000  0.000000        0.00000
REMARK 350   BIOMT3   2  0.000000  0.000000  1.000000        0.00000
REMARK 350   BIOMT1   3  0.000000 -1.000000  0.000000        0.00000
REMARK 350   BIOMT2   3  1.000000  0.000000  0.000000        0.00000
REMARK 350   BIOMT3   3  0.000000  0.000000  1.000000        0.00000
ATOM      1  CA  ALA A   1      10.000   2.000   3.000  1.00  0.00           C
"""


def test_el_generador_dice_de_que_cadena_y_operador_sale_cada_una():
    ensamblaje = generar_unidad_biologica(_DEPOSITO, pdb_id="6SXC")
    assert ensamblaje.generado
    assert ensamblaje.generadas == (("B", "A", 2), ("C", "A", 3))
    linea_c = next(l for l in ensamblaje.pdb.splitlines() if l.startswith("ATOM") and l[21] == "C")
    assert linea_c[30:54] == f"{-2.0:8.3f}{10.0:8.3f}{3.0:8.3f}"


def test_sin_simetria_no_hay_nada_que_declarar():
    sin_biomt = "".join(l + "\n" for l in _DEPOSITO.splitlines() if not l.startswith("REMARK"))
    assert generar_unidad_biologica(sin_biomt).generadas == ()


def _caso(ensamblaje: dict | None):
    caso = _con_procedencia()
    prep = caso["eval_result"].docking_protocol["execution_provenance"]["receptor_prep"]
    prep.update({"chain": "A", "site_chains": ["A", "C"], "prepared_chains": ["A", "C"]})
    if ensamblaje is not None:
        prep["biological_assembly"] = ensamblaje
    return caso


ENSAMBLAJE = {"biomolecule": 1, "operators": 4, "source_chains": ["A"],
              "generated_chains": [{"chain": "B", "from_chain": "A", "biomt_operator": 2},
                                   {"chain": "C", "from_chain": "A", "biomt_operator": 3},
                                   {"chain": "D", "from_chain": "A", "biomt_operator": 4}]}


def test_preparacion_nombra_la_cadena_generada_del_receptor_y_su_operador():
    cadenas = _requisito(_auditar(_caso(ENSAMBLAJE)), "receptor.cadenas")
    assert cadenas["valor"] == ("cadena A · sitio entre A+C · generada(s) por simetría desde el depósito "
                                "(REMARK 350, BIOMOLECULE 1): C←A (BIOMT 3)")
    ingles = _requisito(traducir_dossier(_auditar(_caso(ENSAMBLAJE)), "en"), "receptor.cadenas")
    assert ingles["valor"] == ("chain A · site between A+C · generated by symmetry from the deposit "
                               "(REMARK 350, BIOMOLECULE 1): C←A (BIOMT 3)")
    assert not _PARECE_CASTELLANO.search(ingles["valor"])


def test_sin_ensamblaje_generado_el_texto_de_siempre_y_ahora_traducido():
    cadenas = _requisito(_auditar(_caso(None)), "receptor.cadenas")
    assert cadenas["valor"] == "cadena A · sitio entre A+C"
    ingles = _requisito(traducir_dossier(_auditar(_caso(None)), "en"), "receptor.cadenas")
    assert ingles["valor"] == "chain A · site between A+C"
