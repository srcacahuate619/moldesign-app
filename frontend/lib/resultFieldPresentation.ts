export const RESULT_FIELD_PRESENTATION: Readonly<Record<string, ResultFieldPresentation>> = Object.fromEntries(rows.map(([key,group,es,en,aliases]) => [key,{group,es,en,aliases}]));
export function resultFieldPresentation(key: string): ResultFieldPresentation {
  return RESULT_FIELD_PRESENTATION[key] ?? {group:"other",es:key,en:key};
}
export function normalizeResultSearch(value: string): string {
  return value.normalize("NFKD").replace(/[\u0300-\u036f]/g, "").replace(/[_-]+/g," ").toLocaleLowerCase().trim();
}
export function resultFieldMatches(key: string, value: unknown, query: string): boolean {
  const meta=resultFieldPresentation(key);
  const haystack=normalizeResultSearch(`${key} ${meta.es} ${meta.en} ${meta.aliases ?? ""} ${JSON.stringify(value) ?? ""}`);
  return normalizeResultSearch(query).split(/\s+/).every(term=>haystack.includes(term));
}
